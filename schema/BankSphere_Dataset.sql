CREATE TABLE Branches (
    BranchID      INT IDENTITY(1,1) PRIMARY KEY,
    BranchName    VARCHAR(100) NOT NULL,
    City          VARCHAR(50) NOT NULL
);

CREATE TABLE Customers (
    CustomerID      INT IDENTITY(1,1) PRIMARY KEY,
    FirstName       VARCHAR(50) NOT NULL,
    LastName        VARCHAR(50) NOT NULL,
    Phone           VARCHAR(15) NULL,
    AadhaarNumber   VARCHAR(12) NULL,
    City            VARCHAR(50) NOT NULL,
    AccountOpenDate DATE NOT NULL
);

CREATE TABLE Accounts (
    AccountID     INT IDENTITY(1,1) PRIMARY KEY,
    CustomerID    INT NOT NULL FOREIGN KEY REFERENCES Customers(CustomerID),
    BranchID      INT NOT NULL FOREIGN KEY REFERENCES Branches(BranchID),
    AccountType   VARCHAR(20) NOT NULL,   -- Savings, Current
    Balance       DECIMAL(12,2) NOT NULL,
    Status        VARCHAR(20) NOT NULL    -- Active, Inactive
);

CREATE TABLE Transactions (
    TransactionID   INT IDENTITY(1,1) PRIMARY KEY,
    AccountID       INT NOT NULL FOREIGN KEY REFERENCES Accounts(AccountID),
    TransactionType VARCHAR(20) NOT NULL,  -- Deposit, Withdrawal, Transfer
    Amount          DECIMAL(12,2) NOT NULL,
    TransactionDate DATE NOT NULL,
    Status          VARCHAR(20) NOT NULL   -- Success, Failed, Pending
);

CREATE TABLE Loans (
    LoanID        INT IDENTITY(1,1) PRIMARY KEY,
    CustomerID    INT NOT NULL FOREIGN KEY REFERENCES Customers(CustomerID),
    LoanType      VARCHAR(20) NOT NULL,   -- Home, Personal, Car, Education
    LoanAmount    DECIMAL(12,2) NOT NULL,
    EMIAmount     DECIMAL(10,2) NOT NULL,
    StartDate     DATE NOT NULL,
    Status        VARCHAR(20) NOT NULL    -- Active, Closed, Defaulted
);
GO

